  onEvent: (fn) => ipcRenderer.on('worker-event', (e, m) => fn(m)),
  onSysStats: (fn) => ipcRenderer.on('sys-stats', (e, d) => fn(d)),
  onGcNow: (fn) => ipcRenderer.on('gc-now', () => fn()),
