  assetsStatus: (o) => ipcRenderer.invoke('assets-status', o),
  markInstalled: (t, k, n, p, c) => ipcRenderer.invoke('mark-installed', t, k, n, p, c),
  engineRemove: (v) => ipcRenderer.invoke('engine-remove', v),
  engineInstall: (tarPath, v) => ipcRenderer.invoke('engine-install', tarPath, v),
  removeFile: (p) => ipcRenderer.invoke('remove-file', p),
  repairCheck: () => ipcRenderer.invoke('repair-check'),
  repairFix: (keys) => ipcRenderer.invoke('repair-fix', keys),
  recordInput: (o) => ipcRenderer.invoke('record-input', o),
  pickFiles: () => ipcRenderer.invoke('pick-files'),
  pickDir: () => ipcRenderer.invoke('pick-dir'),
  pickImage: () => ipcRenderer.invoke('pick-image'),
  pickVideo: () => ipcRenderer.invoke('pick-video'),
  setBackground: (p) => ipcRenderer.invoke('set-background', p),
  clearBackground: () => ipcRenderer.invoke('clear-background'),
  getInputFiles: () => ipcRenderer.invoke('get-input-files'),
  openFolder: (p) => ipcRenderer.invoke('open-folder', p),
