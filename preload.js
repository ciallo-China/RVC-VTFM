  onQueueStatus: (fn) => ipcRenderer.on('queue-status', (e, d) => fn(d)),
  pickSavePath: (def) => ipcRenderer.invoke('pick-save-path', def),
  checkPaths: (list) => ipcRenderer.invoke('check-paths', list),
  saveText: (name, text) => ipcRenderer.invoke('save-text', name, text),
  openUrl: (u) => ipcRenderer.invoke('open-url', u),
  openGame: (id) => ipcRenderer.invoke('open-game-window', id),
  openPlaza: () => ipcRenderer.invoke('open-plaza-window'),
